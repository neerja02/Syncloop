import "server-only";
import { getDb } from "@/lib/database/client";
import { assertProfileAccess } from "@/lib/security/access";
import { ageFromDob } from "@/lib/utils/format";
import type { Actor } from "@/types/domain";

/** Plain-text summary that can be shown to responders: identity basics, conditions, allergies, medicines, contacts. */
export async function emergencySummary(actor: Actor, profileId: string) {
  await assertProfileAccess(actor, profileId);
  const db = await getDb();
  const p = (await db.query<{ display_name: string; date_of_birth: string | null; sex: string | null; blood_group: string | null; weight_kg: number | null }>("select display_name, date_of_birth, sex, blood_group, weight_kg from profiles where id = $1", [profileId])).rows[0]!;
  const conditions = (await db.query<{ name: string }>("select name from health_conditions where profile_id = $1 and status <> 'resolved'", [profileId])).rows.map((r) => r.name);
  const allergies = (await db.query<{ substance: string; reaction: string | null }>("select substance, reaction from allergies where profile_id = $1", [profileId])).rows.map((a) => a.substance + (a.reaction ? ` (${a.reaction})` : ""));
  const meds = (await db.query<{ name: string; strength: string | null; frequency: string | null }>("select name, strength, frequency from medications where profile_id = $1 and status = 'active'", [profileId])).rows.map((m) => [m.name, m.strength, m.frequency].filter(Boolean).join(" "));
  const contacts = (await db.query<{ name: string; phone: string; relationship: string | null }>("select name, phone, relationship from emergency_contacts where profile_id = $1", [profileId])).rows;
  const age = ageFromDob(p.date_of_birth);
  const lines = [
    `MEDICAL SUMMARY — ${p.display_name}`,
    [age != null ? `Age ${age}` : null, p.sex, p.blood_group ? `Blood group ${p.blood_group}` : null, p.weight_kg ? `${p.weight_kg} kg` : null].filter(Boolean).join(" · "),
    `Conditions: ${conditions.join(", ") || "None recorded"}`,
    `Allergies: ${allergies.join(", ") || "None recorded"}`,
    `Current medicines: ${meds.join("; ") || "None recorded"}`,
    `Emergency contacts: ${contacts.map((c) => `${c.name}${c.relationship ? ` (${c.relationship})` : ""} ${c.phone}`).join("; ") || "None recorded"}`,
    `Generated by Kinwell ${new Date().toLocaleString("en-GB")}`,
  ];
  return { profile: p, age, conditions, allergies, meds, contacts, text: lines.join("\n") };
}
